"""Load the 311 style CSV into SQLite and run all 10 questions.

Uses only the Python standard library (sqlite3, csv) plus pandas
if it happens to be available for display. No server is needed.

Steps:
1. Create a fresh SQLite database at data/requests_311.db
2. Create the requests_311 table (SQLite version of sql/01_schema.sql)
3. Load data/requests_311.csv (generate it first if missing)
4. Run the 10 queries from src/queries_sqlite.py
5. Print results to stdout and write reports/answers.md
"""

import csv
import sqlite3
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
CSV_PATH = BASE_DIR / "data" / "requests_311.csv"
DB_PATH = BASE_DIR / "data" / "requests_311.db"
REPORT_PATH = BASE_DIR / "reports" / "answers.md"

sys.path.insert(0, str(BASE_DIR / "src"))
from queries_sqlite import QUERIES  # noqa: E402

SCHEMA_SQL = """
DROP TABLE IF EXISTS requests_311;
CREATE TABLE requests_311 (
    unique_key INTEGER PRIMARY KEY,
    created_date TEXT NOT NULL,
    closed_date TEXT,
    agency TEXT NOT NULL,
    complaint_type TEXT NOT NULL,
    descriptor TEXT,
    borough TEXT NOT NULL,
    status TEXT NOT NULL,
    resolution_hours REAL
);
CREATE INDEX idx_borough ON requests_311 (borough);
CREATE INDEX idx_agency ON requests_311 (agency);
CREATE INDEX idx_created ON requests_311 (created_date);
"""


def ensure_csv():
    if not CSV_PATH.exists():
        print(f"CSV not found at {CSV_PATH}, generating synthetic data...")
        import generate_data

        generate_data.main()


def load_csv(conn: sqlite3.Connection) -> int:
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = []
        for row in reader:
            rows.append(
                (
                    int(row["unique_key"]),
                    row["created_date"],
                    row["closed_date"] or None,
                    row["agency"],
                    row["complaint_type"],
                    row["descriptor"] or None,
                    row["borough"],
                    row["status"],
                    float(row["resolution_hours"]) if row["resolution_hours"] else None,
                )
            )
    conn.executemany(
        """
        INSERT INTO requests_311
            (unique_key, created_date, closed_date, agency, complaint_type,
             descriptor, borough, status, resolution_hours)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        rows,
    )
    conn.commit()
    return len(rows)


def format_table(headers, rows, max_rows=15):
    """Return a simple markdown table for the given rows."""
    display_rows = rows[:max_rows]
    lines = []
    lines.append("| " + " | ".join(str(h) for h in headers) + " |")
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for r in display_rows:
        cells = ["" if v is None else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    if len(rows) > max_rows:
        lines.append(f"\n_Showing {max_rows} of {len(rows)} rows._")
    return "\n".join(lines)


def main():
    ensure_csv()
    if DB_PATH.exists():
        DB_PATH.unlink()
    conn = sqlite3.connect(DB_PATH)
    try:
        conn.executescript(SCHEMA_SQL)
        n = load_csv(conn)
        print(f"Loaded {n} rows into SQLite database at {DB_PATH}")
        print()

        report_lines = []
        report_lines.append("# SQL Analytics: Answers from Synthetic Demo Data")
        report_lines.append("")
        report_lines.append(
            "These answers were generated by running `src/load_and_run.py` "
            "against the bundled synthetic NYC 311 style data "
            "(`data/requests_311.csv`, 5000 rows, seed 42). "
            "They are demo findings from synthetic data, not real 311 results."
        )
        report_lines.append("")
        report_lines.append(f"Total rows loaded: {n}")
        report_lines.append("")

        for q in QUERIES:
            cur = conn.execute(q["sql"])
            headers = [d[0] for d in cur.description]
            rows = cur.fetchall()
            print(f"Q{q['id']}: {q['question']}")
            print(f"  Columns: {headers}")
            print(f"  Rows returned: {len(rows)}")
            for r in rows[:5]:
                print(f"  {r}")
            print()

            report_lines.append(f"## Q{q['id']}: {q['question']}")
            report_lines.append("")
            report_lines.append(format_table(headers, rows, max_rows=15))
            report_lines.append("")

        REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        REPORT_PATH.write_text("\n".join(report_lines), encoding="utf-8")
        print(f"Wrote report to {REPORT_PATH}")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
